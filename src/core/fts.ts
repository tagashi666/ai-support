/**
 * Запрос к FTS5 из свободного текста клиента.
 *
 * Токенизатор unicode61 морфологии не знает: «оплатила», «оплата» и
 * «оплатить» для него три разных слова. Полноценный стеммер ради этого
 * тащить незачем — хватает срезать типичное окончание и искать по основе
 * как по префиксу (`оплат*`). Основу ограничиваем по длине: у длинных
 * слов суффиксы плавают сильнее окончаний («подключается» / «подключение»).
 */

// Порядок важен: длинные окончания раньше коротких, иначе «-ами» съелось бы как «-и».
const ENDINGS = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ией', 'иях', 'иям', 'ием',
  'ать', 'ять', 'ить', 'еть', 'уть', 'ила', 'ала', 'яла', 'ела', 'ыла', 'или', 'али', 'ели', 'ыли',
  'ешь', 'ете', 'ите', 'ует', 'уют', 'ают', 'яют', 'ает', 'яет', 'ует',
  'ют', 'ут', 'ит', 'ат', 'ят', 'ет', 'ем', 'им', 'ом', 'ой', 'ей', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее',
  'ые', 'ие', 'ую', 'юю', 'ах', 'ях', 'ов', 'ев', 'ам', 'ям', 'ил', 'ал', 'ел',
  'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 'й',
];

const MIN_STEM = 4;
const MAX_STEM = 7;

/** Основа русского слова для префиксного поиска. Латиницу и цифры не трогаем. */
export function stemRu(word: string): string {
  const lower = word.toLocaleLowerCase('ru').replace(/ё/g, 'е');
  if (!/^[а-я]+$/.test(lower) || lower.length <= MIN_STEM) return lower;
  let stem = lower.replace(/(?:ся|сь)$/, '');
  for (const ending of ENDINGS) {
    if (stem.endsWith(ending) && stem.length - ending.length >= MIN_STEM) {
      stem = stem.slice(0, -ending.length);
      break;
    }
  }
  return stem.slice(0, MAX_STEM);
}

/** Слова, которые ищутся почти везде и только размывают ранжирование. */
const STOP = new Set([
  'что', 'как', 'это', 'для', 'при', 'или', 'так', 'там', 'тут', 'уже', 'еще', 'ещё', 'все', 'всё',
  'мне', 'меня', 'вас', 'вам', 'нас', 'нам', 'его', 'она', 'они', 'оно', 'был', 'была', 'было',
  'есть', 'нет', 'если', 'когда', 'где', 'почему', 'можно', 'нужно', 'надо', 'пожалуйста', 'здравствуйте',
  'привет', 'добрый', 'день', 'вечер', 'спасибо', 'просто', 'очень', 'тоже', 'вот', 'чтобы', 'потом',
]);

/**
 * Слова запроса → выражение MATCH через OR. Служебные символы FTS5 в
 * запрос не попадают: каждое слово берётся в кавычки.
 */
export function ftsExpression(query: string, maxTerms = 12): string {
  const terms: string[] = [];
  for (const word of query.toLocaleLowerCase('ru').split(/[^\p{L}\p{N}]+/u)) {
    if (word.length <= 2 || STOP.has(word)) continue;
    const stem = stemRu(word).replace(/"/g, '');
    if (stem && !terms.includes(stem)) terms.push(stem);
    if (terms.length >= maxTerms) break;
  }
  return terms.map((term) => `"${term}"*`).join(' OR ');
}
