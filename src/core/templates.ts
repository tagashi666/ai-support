export function seedTemplates(store: Store): void {
  // Новые встроенные шаблоны доезжают и на существующие установки, но
  // пользовательские правки к уже известным shortcut не перетираются.
  const existing = new Set(store.listTemplates().map((template) => template.shortcut));
  for (const template of SEED) {
    if (!existing.has(template.shortcut)) store.upsertTemplate(template.shortcut, template.title, template.body);
  }
}
