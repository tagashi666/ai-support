/**
 * Чистка переписки перед отправкой в модель.
 *
 * Майнинг отправляет наружу сотни сообщений разом, поэтому здесь строже, чем
 * при обычном ответе: ключи подписок и платёжные реквизиты не должны покидать
 * сервер вообще. Порядок правил важен — сначала длинные конструкции
 * (ссылки целиком), потом их обломки.
 */
const RULES: [RegExp, string][] = [
  // Ключи подписок и конфиги — самое ценное, что может утечь.
  [/\b(?:vless|vmess|trojan|ss|ssr|hysteria2?|hy2|tuic|wireguard):\/\/\S+/gi, '[ключ-подписки]'],
  [/https?:\/\/\S*\/(?:sub|subscription|json|clash|mihomo|singbox)\/\S+/gi, '[ссылка-на-подписку]'],

  // Прочие ссылки: в них часто зашит токен в query.
  [/https?:\/\/\S+/gi, '[ссылка]'],

  [/\b[\w.+-]+@[\w-]+\.[\w.-]+\b/g, '[почта]'],
  [/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/gi, '[uuid]'],
  [/\b[0-9a-f]{32,}\b/gi, '[токен]'],

  // Карты: 13–19 цифр, в том числе разбитые пробелами или дефисами.
  [/\b(?:\d[ -]?){13,19}\b/g, '[номер-карты]'],
  [/\b\+?[78][ -]?\(?\d{3}\)?[ -]?\d{3}[ -]?\d{2}[ -]?\d{2}\b/g, '[телефон]'],

  [/\b\d{1,3}(?:\.\d{1,3}){3}\b/g, '[ip]'],
  [/@[A-Za-z][A-Za-z0-9_]{4,31}\b/g, '@клиент'],

  // Telegram id — 9–10 цифр подряд. Идёт последним: раньше него
  // отрабатывают карты и телефоны, иначе он съел бы их куски.
  [/\b\d{9,10}\b/g, '[tg-id]'],
];

export function scrub(text: string): string {
  let cleaned = text;
  for (const [pattern, replacement] of RULES) cleaned = cleaned.replace(pattern, replacement);
  return cleaned.replace(/[ \t]{2,}/g, ' ').trim();
}

/** Осталось ли в тексте что-то похожее на секрет — страховка перед отправкой. */
export function looksSensitive(text: string): boolean {
  return /\b[0-9a-f]{32,}\b|:\/\/|\b\d{9,}\b/i.test(text);
}
